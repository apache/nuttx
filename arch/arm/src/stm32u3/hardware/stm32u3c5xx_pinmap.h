/* Alternate Pin Functions.  This map contains every GPIO alternate
 * function available on the supported device package:
 *
 *   STM32U3C5ZI-Q LQFP144
 *
 * It is derived from the ST device package pinout data.  It also
 * contains the peripheral analog pins represented by the NuttX GPIO
 * pin-map interface.
 *
 * Alternative pin selections are provided with a numeric suffix like _1,
 * _2, etc.  Drivers use the selection without the numeric suffix; board.h
 * must map that name to the pin used by the board.  For example:
 *
 * #define GPIO_FDCAN1_RX GPIO_FDCAN1_RX_1
 *
 * Pull resistors, output type, and slew rate are board-specific and are not
 * encoded here.  Timer channels have separate input and output names to
 * match the NuttX timer driver contracts.
 */

