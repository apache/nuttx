/* EMAC / EMAC Control Module / MDIO register layout for the RM57L843,
 * transcribed from SPNU562A chapter 31 ("EMAC/MDIO Module") and
 * cross-checked against TI's HALCoGen HL_hw_emac.h, HL_hw_emac_ctrl.h and
 * HL_hw_mdio.h.
 *
 * This device implements a single-core CPSW-lite subsystem: only "core 0"
 * exists, so only the C0xxx EMAC Control registers and USERACCESS0 /
 * USERPHYSEL0 MDIO registers are meaningful.  HALCoGen's EMAC_CTRL_CnRXEN()
 * style macros are inherited from a multi-core EMAC variant used on other
 * TI parts and do not apply here - this header only defines the C0
 * registers that actually exist on RM57L843.
 *
 * NOTE: HALCoGen's HL_hw_emac.h defines EMAC_NETOCTETS at offset 0x208,
 * but SPNU562A Section 31.5.50.33 documents the Network Octet Frames
 * Register (NETOCTETS) at offset 0x280; offset 0x208 is actually
 * RXMCASTFRAMES (Section 31.5.50.3).  This appears to be a transcription
 * error in the HALCoGen header.  This file uses the TRM-documented value.
 */

