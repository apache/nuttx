#define EMAC_DESC_PKTLEN_MASK        0x0000ffff
#define EMAC_DESC_PASSCRC            0x04000000
#define EMAC_DESC_TDOWNCMPLT         0x08000000
#define EMAC_DESC_EOQ                0x10000000
#define EMAC_DESC_OWNER              0x20000000
#define EMAC_DESC_EOP                0x40000000
#define EMAC_DESC_SOP                0x80000000

