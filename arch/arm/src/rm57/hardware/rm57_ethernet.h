#define EMAC_DESC_RX_CODEERROR       0x00080000
#define EMAC_DESC_RX_OVERRUN         0x00100000
#define EMAC_DESC_RX_CONTROL         0x00200000
#define EMAC_DESC_RX_UNDERSIZED      0x00400000
#define EMAC_DESC_RX_FRAGMENT        0x00800000
#define EMAC_DESC_RX_OVERSIZE        0x01000000
