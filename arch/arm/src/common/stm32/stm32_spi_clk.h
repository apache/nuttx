#elif defined(CONFIG_ARCH_CHIP_STM32H7)

/* Sources from STM32_RCC_D2CCIP1R_SPI123SRC, STM32_RCC_D2CCIP1R_SPI45SRC
 * and STM32_RCC_D3CCIPR_SPI6SRC in board.h, else the reset value (PLL1Q,
 * PCLK2, PCLK4)
 */

#  if !defined(STM32_RCC_D2CCIP1R_SPI123SRC) || \
      STM32_RCC_D2CCIP1R_SPI123SRC == RCC_D2CCIP1R_SPI123SEL_PLL1
#    define STM32_SPI123_KERCLK  STM32_PLL1Q_FREQUENCY
#  elif STM32_RCC_D2CCIP1R_SPI123SRC == RCC_D2CCIP1R_SPI123SEL_PLL2
#    define STM32_SPI123_KERCLK  STM32_PLL2P_FREQUENCY
#  elif STM32_RCC_D2CCIP1R_SPI123SRC == RCC_D2CCIP1R_SPI123SEL_PLL3
#    define STM32_SPI123_KERCLK  STM32_PLL3P_FREQUENCY
#  endif

#  if !defined(STM32_RCC_D2CCIP1R_SPI45SRC) || \
      STM32_RCC_D2CCIP1R_SPI45SRC == RCC_D2CCIP1R_SPI45SEL_APB
#    define STM32_SPI45_KERCLK   STM32_PCLK2_FREQUENCY
#  elif STM32_RCC_D2CCIP1R_SPI45SRC == RCC_D2CCIP1R_SPI45SEL_PLL2
#    define STM32_SPI45_KERCLK   STM32_PLL2Q_FREQUENCY
#  elif STM32_RCC_D2CCIP1R_SPI45SRC == RCC_D2CCIP1R_SPI45SEL_PLL3
#    define STM32_SPI45_KERCLK   STM32_PLL3Q_FREQUENCY
#  elif STM32_RCC_D2CCIP1R_SPI45SRC == RCC_D2CCIP1R_SPI45SEL_HSI
#    define STM32_SPI45_KERCLK   STM32_HSI_FREQUENCY
#  elif STM32_RCC_D2CCIP1R_SPI45SRC == RCC_D2CCIP1R_SPI45SEL_CSI
#    define STM32_SPI45_KERCLK   STM32_CSI_FREQUENCY
#  elif STM32_RCC_D2CCIP1R_SPI45SRC == RCC_D2CCIP1R_SPI45SEL_HSE
#    define STM32_SPI45_KERCLK   STM32_HSE_FREQUENCY
#  endif

#  if !defined(STM32_SPI1_FREQUENCY) && defined(STM32_SPI123_KERCLK)
#    define STM32_SPI1_FREQUENCY  STM32_SPI123_KERCLK
#  endif

#  if !defined(STM32_SPI2_FREQUENCY) && defined(STM32_SPI123_KERCLK)
#    define STM32_SPI2_FREQUENCY  STM32_SPI123_KERCLK
#  endif

#  if !defined(STM32_SPI3_FREQUENCY) && defined(STM32_SPI123_KERCLK)
#    define STM32_SPI3_FREQUENCY  STM32_SPI123_KERCLK
#  endif

#  if !defined(STM32_SPI4_FREQUENCY) && defined(STM32_SPI45_KERCLK)
#    define STM32_SPI4_FREQUENCY  STM32_SPI45_KERCLK
#  endif

